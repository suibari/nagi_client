<h2 id="t1">1. 定義</h2>
<p>
	本サービスは、AT
	Protocol上で動作する全肯定SNSです。あなたの投稿はあなた自身のアカウント（PDS）に保存され、本サービスはそれを表示・検索するためのAppViewとして動作します。
</p>
<ul>
	<li>
		<strong>本サービス</strong>: Nagi（nagi.suibari.com）およびこれに付随して運営者が提供する機能。
	</li>
	<li>
		<strong>PDS</strong>: AT
		Protocolにおける、あなたのアカウントとレコードの保管場所。あなたが選んだ事業者、または自分で運用するサーバです。
	</li>
	<li>
		<strong>AppView</strong>:
		PDS上の公開レコードを集めて表示・検索するためのしくみ。本サービスはこれにあたります。
	</li>
	<li><strong>botたん</strong>: 本サービス上で応答する、AIによって動作するキャラクターです。</li>
</ul>


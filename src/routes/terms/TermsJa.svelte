		>その日の投稿にこっそり投稿が含まれる日の日記は、あなただけが読めます。</strong
	>こっそり投稿と同じくPDSには保存しません。他の利用者からは、日付と投稿数（プロフィールの年間グラフのマス）だけが見え、本文は表示されません。
</p>


<h2 id="t8">8. モデレーションおよび違反への対応</h2>
<p>
	安全で健全なコミュニティ運営のため、運営者はAIを用いた自動判定システムを利用しています。本規約に違反する行為やセンシティブな表現が検知された場合、違反の内容と程度に応じて、次のような対応を行います。
</p>
<ol>
	<li>
		<strong>警告・ぼかし（Blur）の付与</strong>:
		センシティブな表現（性的、暴力、閲覧注意等）が含まれると判定されたコンテンツにラベルを付け、クライアント上でのぼかし表示や警告バナーの表示を行います。ラベルの付いたコンテンツは、18歳未満のアカウントには表示されません。
	</li>
	<li>
		<strong>本サービス（AppView）での保存拒否</strong>:
		露骨な性的コンテンツ、過度な暴力表現、未成年者の性的表現、その他の深刻な規約違反（ヘイト、脅迫等）と判定されたコンテンツは、本サービスのデータベースへ保存せず、本サービス上で一切表示されない措置をとることがあります。
	</li>
	<li>本サービス上での該当コンテンツの非表示</li>
	<li>利用者への注意および一部機能の利用制限</li>
	<li>本サービス上でのアカウントの表示停止</li>
	<li>法令に基づく、捜査機関等への通報</li>
</ol>
<div class="callout warn">
	<p>
		<strong
			>本サービス上で非表示または保存拒否としても、あなたのPDSからレコードが削除されるわけではありません。</strong
		>本サービスはAppViewであり、投稿の実体はあなたのPDSにあります。完全に削除するには、あなた自身がPDS側でレコードを削除する必要があります。また、他のAppViewが同じ公開レコードを表示することを、運営者が止めることはできません。ただし「こっそり投稿」と、それを含む日の日記はPDSに実体が無いため、本サービス上で削除すれば完全に消えます。
	</p>

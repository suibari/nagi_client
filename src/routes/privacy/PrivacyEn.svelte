<h2 id="p1">1. Terms used here</h2>
<p>
	The Service is an AppView running on the AT Protocol.
	<strong>
		The authoritative copy of your posts lives in your own PDS; the Service keeps a copy for display
		and search, plus data derived from it.
	</strong>
	"Kossori" (quiet) posts, and the diaries for days that contain one, are the exception:
	<strong>their only copy lives on the Service's servers</strong> (putting them in a PDS would make them
	readable by anyone). This Policy sets out which information is stored where.
</p>
<ul>
	<li>
		<strong>PDS</strong>: Where your account and records live on the AT Protocol — a provider you
		chose, or a server you run yourself. The operator of the Service does not run it.
	</li>
	<li>
		<strong>Our servers</strong>: The servers the operator runs to provide timelines and search (the
		AppView and Bot-tan's server).
	</li>
	<li><strong>Bot-tan</strong>: The AI-powered character that responds on the Service.</li>
</ul>

<h2 id="p2">2. What we store on our servers</h2>
<p>
	Your PDS holds the authoritative copy of your posts. This section lists what
	<strong>we keep on our own servers</strong> in addition to that.
</p>
<ul>
	<li>
		<strong>Post text and link cards.</strong> A copy, used to render timelines and to search. We do not
		store the attached images themselves — we fetch them from your PDS and relay them each time they are
		displayed.
	</li>
	<li><strong>Reactions, profile, channels, and custom emoji.</strong> Also copies.</li>
	<li>
		<strong>The text of "Kossori" posts, and of the diaries for days that contain one.</strong>
		These are not copies but the <strong>only</strong> copy. They are visible to no one but you and Bot-tan.
		Putting them in a PDS would make them readable by anyone, so we keep them only on our servers — the
		same reasoning as for mute settings and your Home list. In exchange, they are lost if the Service
		shuts down and cannot be taken to another app. Kossori posts made before 18 August 2026 also remain
		in your PDS, as the design at the time required.
	</li>
	<li><strong>Your DID, handle, and PDS URL.</strong></li>
	<li>
		<strong>Semantic vectors.</strong> Derived from your posts and profile, used to power search.
	</li>
	<li>
		<strong>Text generated by Bot-tan.</strong> Replies to you, your analysis, diaries, card comments,
		and anonymous "Affirm together" summaries. A summary is stored with the original post's URI and CID.
		When the original is a Kossori post, that URI is an identifier issued by the Service that contains
		no author DID, so neither the summary nor a reaction to it can be traced back to the author.
	</li>
	<li><strong>Your conversation history with Bot-tan.</strong></li>
	<li><strong>Notifications and read state.</strong></li>
	<li>
		<strong>Push notification destinations.</strong> The endpoint URL and encryption keys, stored only
		if you enable notifications.
	</li>
	<li>
		<strong>Mute settings.</strong> Visible only to you. We keep these on our servers rather than in your
		PDS because records there are readable by anyone, which would make public who you have muted.
	</li>
	<li>
		<strong>Your Home list.</strong> Visible only to you. We keep it on our servers rather than in your
		PDS so the people you add are not made public.
	</li>
	<li>
		<strong>Bookmarks and folders.</strong> We store only folder names and the URIs of bookmarked items
		and the last-used folder ID on our servers, visible only to you. They are not stored in your PDS,
		and we do not create a snapshot of the bookmarked content.
	</li>
	<li>
		<strong>Drafts and synced settings.</strong> For drafts without images, we store text, mentions, channels,
		Bluemoji, link URL/title/description, and quote URI, plus post and translation settings, visible only
		to you. We do not store images, link thumbnails, or other binary data.
	</li>
	<li>
		<strong>“Affirm together” dismissals.</strong> We store dismissed post URIs, visible only to you,
		and delete them when the seven-day candidate period ends.
	</li>
	<li><strong>Translation cache and card collection records.</strong></li>
</ul>
<p>
	As features are added, the information we handle may grow. We will announce significant changes as
	revisions to this Policy.
</p>

<h2 id="p3">3. What we do not collect</h2>
<ul>
	<li><strong>Passwords</strong>: You sign in via OAuth; the operator never receives one.</li>
	<li><strong>Email addresses</strong>: Not needed to sign up, so we do not collect them.</li>
	<li><strong>Payment details, phone numbers, location</strong>: Not collected.</li>
	<li>
		<strong>Advertising or analytics tracking</strong>: The Service carries no advertising and uses
		no analytics tools. It does not use cookies.
	</li>
	<li>
		<strong>IP addresses</strong>: Held briefly in memory to rate-limit excessive access, never
		written to our database. They do appear in our hosting provider's access records (<a href="#p6"
			>Section 6</a
		>).
	</li>
</ul>


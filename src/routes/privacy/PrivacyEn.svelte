<h2 id="p7">7. What is stored on your device</h2>
<p>The Service stores the following in your browser. It is not sent to our servers.</p>
<ul>
	<li>
		<strong>Local storage</strong>: The DID you are signed in as, theme, display language,
		translation settings, crosspost settings, frequently used emoji, and unread positions in
		timelines
	</li>
	<li><strong>IndexedDB</strong>: Your OAuth session, and post drafts</li>
</ul>
<p>
	The Service does not use cookies. These are cleared when you sign out or clear your browser data.
</p>

<h2 id="p8">8. How public your data is</h2>
<ul>
	<li>
		Posts, reactions, and profiles on the Service are public AT Protocol records. Applications other
		than the Service can fetch and display them.
	</li>
	<li>Mute settings are visible only to you. The person you muted is not notified.</li>
</ul>
<div class="callout warn">
	<p>
		<strong>"Kossori" (quiet) posts are not private.</strong> They are hidden from the Service's timelines,
		but they are stored in your PDS as ordinary public records, and their text is stored on our servers
		too. Please do not post anything you need to keep secret.
	</p>
</div>

<h2 id="p9">9. Retention and deletion</h2>
<div class="callout">
	<p>
		From "Delete data" in Settings, you can
		<strong>delete all of your data described in this Policy from our servers.</strong> This cannot be
		undone.
	</p>
</div>

<h3>What is deleted</h3>
<ul>
	<li>Copies of your posts, reactions, profile, and channels</li>
	<li>Semantic vectors used for search</li>
	<li>AI-generated analysis, diaries, and card comments</li>
	<li>Your conversation history with Bot-tan</li>
	<li>Notifications, push notification destinations, and mute settings</li>
</ul>

<h3>What is not deleted</h3>
<ul>
	<li>
		<strong>Records in your PDS.</strong> The Service cannot delete them. To remove them completely you
		must delete them from your PDS yourself.
	</li>
	<li>Logs Google keeps for abuse detection (deleted within 55 days).</li>
	<li>
		Copies of public records fetched or cached by other AppViews or search engines. These are outside
		the operator's control.
	</li>
</ul>
<p>
	We keep a record of how often features are used for statistical purposes; when you delete your
	data, we unlink those records from your DID.
</p>


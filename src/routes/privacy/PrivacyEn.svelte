<h2 id="p1">1. Terms used here</h2>
<p>
	The Service is an AppView running on the AT Protocol.
	<strong>
		The authoritative copy of your posts lives in your own PDS; the Service keeps a copy for display
		and search, plus data derived from it.
	</strong> This Policy sets out which information is stored where.
</p>
<ul>
	<li>
		<strong>PDS</strong>: Where your account and records live on the AT Protocol — a provider you
		chose, or a server you run yourself. The operator of the Service does not run it.
	</li>
	<li>
		<strong>Our servers</strong>: The servers the operator runs to provide timelines and search (the
		AppView and Bot-tan's server).
	</li>
	<li><strong>Bot-tan</strong>: The AI-powered character that responds on the Service.</li>
</ul>

<h2 id="p2">2. What we store on our servers</h2>
<p>
	Your PDS holds the authoritative copy of your posts. This section lists what
	<strong>we keep on our own servers</strong> in addition to that.
</p>
<ul>
	<li>
		<strong>Post text and link cards.</strong> A copy, used to render timelines and to search. We do not
		store the attached images themselves — we fetch them from your PDS and relay them each time they are
		displayed.
	</li>
	<li><strong>Reactions, profile, channels, and custom emoji.</strong> Also copies.</li>
	<li><strong>Your DID, handle, and PDS URL.</strong></li>
	<li>
		<strong>Semantic vectors.</strong> Derived from your posts and profile, used to power search.
	</li>
	<li>
		<strong>Text generated by Bot-tan.</strong> Replies to you, your analysis, diaries, and card comments.
	</li>
	<li><strong>Your conversation history with Bot-tan.</strong></li>
	<li><strong>Notifications and read state.</strong></li>
	<li>
		<strong>Push notification destinations.</strong> The endpoint URL and encryption keys, stored only
		if you enable notifications.
	</li>
	<li>
		<strong>Mute settings.</strong> Visible only to you. We keep these on our servers rather than in your
		PDS because records there are readable by anyone, which would make public who you have muted.
	</li>
	<li><strong>Translation cache and card collection records.</strong></li>
</ul>
<p>
	As features are added, the information we handle may grow. We will announce significant changes as
	revisions to this Policy.
</p>

<h2 id="p3">3. What we do not collect</h2>
<ul>
	<li><strong>Passwords</strong>: You sign in via OAuth; the operator never receives one.</li>
	<li><strong>Email addresses</strong>: Not needed to sign up, so we do not collect them.</li>
	<li><strong>Payment details, phone numbers, location</strong>: Not collected.</li>
	<li>
		<strong>Advertising or analytics tracking</strong>: The Service carries no advertising and uses no
		analytics tools. It does not use cookies.
	</li>
	<li>
		<strong>IP addresses</strong>: Held briefly in memory to rate-limit excessive access, never
		written to our database. They do appear in our hosting provider's access records
		(<a href="#p6">Section 6</a>).
	</li>
</ul>

<h2 id="p4">4. How we use information</h2>
<ul>
	<li>To provide the Service — timelines, profiles, channels, and search</li>
	<li>
		To provide AI features — Bot-tan's replies, automatic analysis, diaries, and card comments
	</li>
	<li>To deliver notifications</li>
	<li>To prevent abuse and excessive load</li>
	<li>To investigate faults and improve the Service</li>
</ul>

<h2 id="p5">5. AI features and what is sent to Google</h2>
<p>
	The Service's AI features use the <strong>Gemini API provided by Google LLC (paid tier)</strong>.
	To provide them, the following is sent to Google:
</p>
<ul>
	<li>The text of your posts and any attached images</li>
	<li>Your profile display name and bio</li>
	<li>
		As context for a reply, your earlier posts and related public posts from other users
	</li>
	<li>Your conversation history with Bot-tan</li>
	<li>Links contained in your posts (Google fetches the content at those URLs)</li>
	<li>
		For the automatic profile analysis, up to 100 of your posts and up to 100 posts you reacted to.
		<strong>
			When you first sign up, up to 100 of your Bluesky posts and 100 of your Bluesky likes are used
			instead.
		</strong>
	</li>
</ul>
<h3>How Google handles it (paid-tier terms)</h3>
<ul>
	<li>
		<strong>
			Google does not use the inputs or the generated outputs to improve or train its products or AI
			models.
		</strong>
	</li>
	<li>
		Logs are retained for <strong>up to 55 days</strong> to detect and prevent policy violations and to
		meet legal obligations. During that period, Google staff may review content flagged as potentially
		violating.
	</li>
	<li>
		Data may be stored or cached transiently in any country where Google or its agents maintain
		facilities.
	</li>
</ul>
<p>
	Bot-tan's responses and news selection also use Google Search grounding. In that case the search
	queries and the URLs you shared are passed to Google and retained for 30 days.
</p>
<p>
	The Service is limited to people aged 18 or older because the Gemini API terms require it. See
	Section 2 of the <a href="/terms">Terms of Service</a>.
</p>


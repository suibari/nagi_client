<h2 id="p7">7. What is stored on your device</h2>
<p>
	The Service stores the following in your browser. For signed-out post replies and card draws, only
	the information described below is sent to our servers.
</p>
<ul>
	<li>
		<strong>Local storage</strong>: The DID you are signed in as, theme, display language,
		OAuth-related crosspost settings, local caches of synced data, your consent state for signed-out
		AI use, and a random device value and today’s card for signed-out card draws
	</li>
	<li>
		<strong>IndexedDB</strong>: Your OAuth session, legacy device drafts with images that have not
		migrated, and your signed-out “Private on this device” posts and Bot-tan replies
	</li>
</ul>
<p>
	The Service does not use cookies. These are cleared when you sign out or clear your browser data.
</p>
<p>
	Signed-out “Private on this device” posts are not used for public posts, search, “Affirm
	together,” profiles, or automatic analysis. Their text is sent to a short-lived processing area
	only to generate Bot-tan’s reply. It is deleted as soon as your device receives the reply, and
	within 24 hours if delivery does not complete. Section 5 describes handling by the AI provider.
</p>
<p>
	When you draw an Affirmation Card while signed out, the Service sends a random device value to the
	server. The server stores its hash, that day’s card number, and an expiry at the card-day boundary
	to prevent duplicate draws on the same device. If you sign in during that card day, the draw is
	linked to your DID and added to your Card File. The local result is deleted after the boundary,
	and earlier days are not imported later.
</p>

<h2 id="p8">8. How public your data is</h2>
<ul>
	<li>
		Posts, reactions, and profiles on the Service are public AT Protocol records. Nagi's interface
		and AppView do not show third parties who reacted or another person's reaction history. However,
		these public records can still be fetched directly from a PDS or displayed by applications other
		than the Service.
	</li>
	<li>Mute settings are visible only to you. The person you muted is not notified.</li>
	<li>Your Home list is visible only to you. People you add are not notified.</li>
</ul>
<div class="callout warn">
	<p>
		<strong>"Kossori" (quiet) posts are readable only by you and Bot-tan.</strong> Their text is
		stored on our servers rather than in your PDS, and never appears in shared timelines, search,
		threads, or anyone else's profile. Only you and Bot-tan can reply.
		<strong>A diary for a day that contains a Kossori post is treated the same way</strong>: other
		users see only the date and the post count (the cell in the annual graph on your profile).
	</p>
	<p>
		However, <strong
			>an anonymous Bot-tan summary — with neither your name nor the original wording — may appear
			in "Affirm together."</strong
		> The original-post URI stored alongside that summary is an identifier issued by the Service that
		contains no author DID. Readers can react to the summary, but cannot trace it back to you or to the
		original text. Channel-only posts may be summarized in the same way, but they are stored in your PDS
		as ordinary public records.
	</p>
	<p>
		<strong>Kossori posts made before 18 August 2026 remain in your PDS as public records.</strong> The
		Service shows them only to you, but anyone reading your PDS directly can fetch them.
	</p>
</div>

<h2 id="p9">9. Retention and deletion</h2>
<div class="callout">
	<p>
		From "Delete data" in Settings, you can
		<strong>delete all of your data described in this Policy from our servers.</strong> This cannot be
		undone.
	</p>
</div>

<h3>What is deleted</h3>
<ul>
	<li>Copies of your posts, reactions, profile, and channels</li>
	<li>
		<strong>The text of "Kossori" posts and of the diaries containing them.</strong> These have no counterpart
		in any PDS, so this removes them completely.
	</li>
	<li>Nagi post, reaction, and profile records in your PDS</li>
	<li>Custom emoji in your PDS that have a marker showing they were created by Nagi</li>
	<li>Semantic vectors used for search</li>
	<li>AI-generated analysis, diaries, card comments, and anonymous summaries</li>
	<li>Your conversation history with Bot-tan</li>
	<li>
		Notifications, push notification destinations, mute settings, your Home list, bookmarks, and
		folders
	</li>
	<li>
		Channel subscriptions (both yours, and records of other people subscribing to your channels)
	</li>
</ul>
<p>We also delete entries where another user had added you to their Home.</p>

<h3>What is not deleted</h3>
<ul>
	<li>
		<strong>Your visit history and gifts in Bot-tan's Room, and your Discord link.</strong> These belong
		to Bot-tan's Room and community, not to Nagi. They are deliberately left alone so you can keep using
		them after leaving Nagi. If you want them removed, please ask through each of those services.
	</li>
	<li>
		<strong>Other records in your PDS.</strong> This includes Bluemoji created by other apps and Bluemoji
		registered before Nagi introduced creation markers, and Kossori posts made before 18 August 2026,
		which are public records in your PDS (Kossori posts made since then are not in any PDS, so they do
		not apply). To remove them completely, you must delete them from your PDS yourself.
	</li>
	<li>Logs Google keeps for abuse detection (deleted within 55 days).</li>
	<li>
		Copies of public records fetched or cached by other AppViews or search engines. These are
		outside the operator's control.
	</li>
</ul>
<p>
	Reactions by other users that used your custom emoji remain as those users' data. After the
	Service's copy of the emoji is deleted, its fallback name is displayed instead of the image.
</p>
<p>
	We keep a record of how often features are used for statistical purposes; when you delete your
	data, we unlink those records from your DID.
</p>


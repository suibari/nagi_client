<h2 id="p7">7. 端末に保存する情報</h2>
<p>
	本サービスは、あなたのブラウザに次の情報を保存します。未サインインの投稿返信とカード抽選については、後述する情報だけをサーバへ送信します。
</p>
<ul>
	<li>
		<strong>ローカルストレージ</strong>:
		ログイン中のDID、テーマ、表示言語、OAuthに関係するクロスポスト設定、同期データの端末キャッシュ、未サインイン投稿のAI利用への同意状態、未サインインのカード抽選に使う端末用のランダム値と当日のカード
	</li>
	<li>
		<strong>IndexedDB</strong>:
		OAuthのセッション情報、移行前の画像付き旧端末下書き、未サインイン時の「この端末のこっそり」投稿とbotたんの返信
	</li>
</ul>
<p>
	Cookieは使用していません。これらはログアウト、またはブラウザのデータ削除によって消去されます。
</p>
<p>
	未サインイン時の「この端末のこっそり」投稿は、公開投稿、検索、「みんなで全肯定」、プロフィール、自動分析には使用しません。botたんの返信を生成するため、本文を期限付きの処理領域へ送信します。返信を端末が受け取った後は直ちに削除し、受け取れなかった場合も24時間以内に削除します。AI提供者側での取り扱いは第5節のとおりです。
</p>
<p>
	未サインインで全肯定カードを引くと、端末用のランダム値をサーバへ送信します。サーバはそのハッシュ、当日のカード番号、カードの日付境界までの有効期限を保存し、同じ端末での二重抽選を防ぎます。同日中にサインインした場合はDIDと結び付けてカードファイルへ追加します。端末側の当日カードは日付境界を越えると削除され、過去日のカードを後から取り込むことはありません。
</p>

<h2 id="p8">8. 公開範囲について</h2>
<ul>
	<li>
		本サービスの投稿、リアクション、プロフィールは、AT
		Protocolの公開レコードです。Nagiの画面とAppViewでは、第三者にリアクションした人や他人のリアクション履歴を表示しません。ただし、PDSを直接読む場合や本サービス以外のアプリケーションからは、公開レコードとして取得・表示されることがあります。
	</li>
	<li>ミュート設定は、本人以外には表示されません。ミュートした相手にも通知されません。</li>
	<li>ホームで見る人のリストは本人以外には表示されず、追加した相手にも通知されません。</li>
</ul>
<div class="callout warn">
	<p>
		<strong>「こっそり投稿」は、あなたとbotたんだけが読める投稿です。</strong
		>本文はあなたのPDSではなく本サービスのサーバにのみ保存し、共有タイムライン・検索・スレッド・他人のプロフィールのいずれにも出しません。返信できるのはbotたんとあなただけです。<strong
			>こっそり投稿を含む日の日記も同じ扱い</strong
		>で、他の利用者からは日付と投稿数（プロフィールの年間グラフのマス）だけが見えます。
	</p>
	<p>
		ただし、<strong
			>作者名も本文も伏せたbotたんの要約が「みんなで全肯定」に表示される場合があります。</strong
		>要約に対応付ける元投稿のURIは、作者のDIDを含まない本サービス発行の識別子です。要約を読んだ利用者はリアクションを送れますが、そこからあなたや元の本文へ辿ることはできません。チャンネル限定投稿も同じ匿名要約の候補ですが、そちらはあなたのPDS上に通常の公開レコードとして保存されます。
	</p>
	<p>
		<strong
			>2026年8月18日より前に投稿されたこっそり投稿は、あなたのPDS上に公開レコードとして残っています。</strong
		>本サービスの画面からは同じく本人にしか表示されませんが、PDSを直接読めば取得できます。
	</p>
</div>


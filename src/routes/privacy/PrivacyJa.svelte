<h2 id="p5">5. AI機能と外部への送信</h2>
<p>
	本サービスのAI機能の文章は、<strong>運営者が自宅で運用するローカルのAIモデル</strong
	>が作ります。botたんの返信、プロフィールの自動分析、日記、カードのコメント、「みんなで全肯定」の匿名要約、翻訳は、すべてこのモデルによる生成です。
</p>
<p>
	<strong
		>これらの生成のために、あなたの投稿の本文・添付画像・プロフィール・botたんとの会話履歴が、外部の事業者へ送信されることはありません。</strong
	>
</p>
<h3>最新の情報を確かめるときだけ外部検索を使います</h3>
<p>
	天気や、作品・楽曲が実在するかの確認など、最新の事実が必要な場合に限り、運営者が管理する検索システム（SearXNG）を通じて外部の検索エンジンを使います。
</p>
<h3>外部検索で送信・取得する情報</h3>
<ul>
	<li>
		ローカルのAIモデルが組み立てた<strong>検索語</strong
		>を外部の検索エンジンへ送ります。投稿の全文、あなたの名前・ハンドル・DID、会話履歴、botたんの設定文はここに含めません。
	</li>
	<li>
		あなたが投稿に含めたリンクの内容を確認する必要がある場合は、<strong
			>運営者のサーバーがそのURLへ直接アクセス</strong
		>します。リンク先には運営者のサーバーからのアクセス情報が届きますが、あなたのDIDや会話履歴は送りません。
	</li>
</ul>
<p>
	調べた結果はローカルのAIモデルへ戻され、最終的な文面はローカルのAIモデルが書きます。あなたの投稿の本文や画像そのものを、生成AIの提供事業者へ送ることはありません。
</p>
<h3>自動モデレーションのためにOpenAIへ送ります</h3>
<p>
	安心して過ごせる場を保つため、<strong>他の人に表示されるユーザー生成コンテンツ</strong>を、OpenAI,
	Inc.が提供するModeration API（omni-moderation）で判定しています。送るのは次のものです。
</p>
<ul>
	<li>投稿の本文、画像の代替テキスト、リンクカードのタイトルと説明</li>
	<li>
		プロフィールの表示名と自己紹介、チャンネルの名前と説明、カスタム絵文字の名前と代替テキスト
	</li>
	<li>ニュースの見出しと出典名</li>
	<li>
		上記に添付された<strong>公開画像のURL</strong>（画像はOpenAIが本サービス経由で取得します）
	</li>
</ul>
<div class="callout">
	<p>
		<strong>「こっそり投稿」はOpenAIへ送りません。</strong
		>下書き、ブックマーク、設定、botたんが書く日記も送りません。
	</p>
</div>
<h3>OpenAIでの取り扱い</h3>
<ul>

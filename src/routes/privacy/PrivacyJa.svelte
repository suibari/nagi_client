<h2 id="p1">1. 用語</h2>
<p>
	本サービスは、AT Protocol上で動作するAppViewです。<strong
		>あなたの投稿の正本はあなた自身のPDSにあり、本サービスはそれを表示・検索するための複製と、そこから作られた派生データを保持します。</strong
	>ただし「こっそり投稿」と、それを含む日の日記だけは例外で、<strong
		>正本が本サービスのサーバにしかありません</strong
	>（PDSに置くと誰でも読み取れてしまうため）。本ポリシーでは、どの情報がどちらに保存されるのかを明らかにします。
</p>
<ul>
	<li>
		<strong>PDS</strong>: AT
		Protocolにおける、あなたのアカウントとレコードの保管場所。あなたが選んだ事業者、または自分で運用するサーバです。本サービスの運営者はこれを運営していません。
	</li>
	<li>
		<strong>本サービスのサーバ</strong>:
		タイムラインや検索を提供するために運営者が管理しているサーバ（AppViewおよびbotたんのサーバ）です。
	</li>
	<li><strong>botたん</strong>: 本サービス上で応答する、AIによって動作するキャラクターです。</li>
</ul>

<h2 id="p2">2. 本サービスのサーバに保存する情報</h2>
<p>
	投稿などの正本はあなたのPDSにあります。ここでは、それとは別に<strong
		>本サービスのサーバ側に残るもの</strong
	>を挙げます。
</p>
<ul>
	<li>
		<strong>投稿の本文とリンクカード。</strong
		>タイムラインの表示と検索のための複製です。添付画像は実体を保存せず、表示のたびにあなたのPDSから取得して中継します。
	</li>
	<li><strong>リアクション、プロフィール、チャンネル、カスタム絵文字。</strong>同じく複製です。</li>
	<li>
		<strong>「こっそり投稿」の本文と、それを含む日の日記。</strong>これらは複製ではなく<strong
			>正本</strong
		>です。本人とbotたん以外には見えません。PDSに置くと誰でも読み取れてしまうため、本サービスのサーバにのみ保存しています（ミュート設定やホームのリストと同じ考え方です）。そのぶん、本サービスが終了すれば失われ、他のアプリへ持ち出すこともできません。なお、2026年8月18日より前のこっそり投稿は、当時の仕様どおりあなたのPDSにも残っています。
	</li>
	<li><strong>DID、ハンドル、あなたのPDSのURL。</strong></li>
	<li><strong>意味ベクトル。</strong>投稿やプロフィールから作る、検索のためのデータです。</li>
	<li>
		<strong>botたんが生成した文章。</strong
		>あなたへの返信、あなたの分析、日記、カードのコメント、「みんなで全肯定」の匿名要約です。匿名要約には元投稿のURIとCIDを対応付けて保存します。元投稿がこっそり投稿の場合、そのURIは作者のDIDを含まない本サービス発行の識別子なので、要約やリアクションから作者を辿ることはできません。
	</li>
	<li><strong>botたんとの会話履歴。</strong></li>
	<li><strong>通知と既読の状態。</strong></li>
	<li>
		<strong>プッシュ通知の配信先。</strong
		>エンドポイントURLと暗号鍵で、通知を有効にした場合にのみ保存します。
	</li>
	<li>
		<strong>ミュート設定。</strong
		>本人以外には見えません。PDSに置くと誰でも読み取れてしまい、「誰をミュートしているか」が公開されるため、本サービスのサーバにのみ保存しています。
	</li>
	<li>
		<strong>ホームで見る人のリスト。</strong
		>本人以外には見えません。誰をホームに追加したかが公開されないよう、PDSではなく本サービスのサーバにのみ保存しています。
	</li>
	<li>
		<strong>ブックマークとフォルダ。</strong
		>フォルダ名、保存対象のURI、最後に使用したフォルダIDを本人限定で本サービスのサーバに保存します。何を保存したかが公開されないよう、PDSには保存しません。本文の保存時点の複製は作りません。
	</li>
	<li>
		<strong>下書きと同期設定。</strong
		>画像を含まない下書きの本文、メンション、チャンネル、Bluemoji、リンクのURL・タイトル・説明、引用URIと、投稿・翻訳設定を本人限定で保存します。画像、リンクサムネイルその他のバイナリは保存しません。
	</li>
	<li>
		<strong>「みんなで全肯定」の見送り。</strong
		>見送った投稿URIを本人限定で保存し、候補期間（投稿から7日間）が終わると削除します。
	</li>
	<li><strong>翻訳のキャッシュ、カードの所持記録。</strong></li>
</ul>
<p>
	機能の追加により、取り扱う情報が増えることがあります。重要な変更については、本ポリシーの改訂として告知します。
</p>

<h2 id="p3">3. 取得しない情報</h2>
<ul>
	<li><strong>パスワード</strong>: ログインはOAuthで行われ、運営者が受け取ることはありません。</li>
	<li><strong>メールアドレス</strong>: 登録に必要ないため、取得していません。</li>
	<li><strong>支払情報、電話番号、位置情報</strong>: 取得していません。</li>
	<li>
		<strong>広告・アクセス解析のためのトラッキング</strong>:
		本サービスは広告を掲載しておらず、アクセス解析ツールも導入していません。Cookieも使用していません。
	</li>
	<li>
		<strong>IPアドレス</strong>:
		過度なアクセスを制限するために一時的にメモリ上で扱いますが、本サービスのデータベースには保存しません。ただし、ホスティング事業者のアクセス記録には残ります（<a
			href="#p6">第6条</a
		>）。
	</li>
</ul>

